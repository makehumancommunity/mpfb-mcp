"""
The ``mpfb_refit_human`` tool: bring a character's assets and rig back into fit.

Exists because ``refit`` defaults to *false* on every modeling tool here, the
way it does in MPFB's own model panel. A refit re-runs the vertex fit for every
garment and proxy on the character and re-fits the armature, which is expensive
enough that MPFB does not want it on every slider drag - but changing a body's
shape moves it out from under everything fitted to it. Without a standalone
refit, that default would leave an agent able to deform a dressed character with
no way to put it right.

So this is the tool the modeling tools point at: change what needs changing,
then refit once at the end.

The one failure worth knowing about is invisible from inside MPFB's own API.
``HumanService.refit()`` reports "generated Rigify rig with no meta rig" through
an ``operator`` argument this layer has no operator to pass, and otherwise
returns having refitted the mesh assets but silently not the rig. The condition
is therefore detected on the far side of the socket and reported here instead -
by ``bridge/mpfb_bridge/commands/refit_human.py``, which shares one statement of
the condition with the three other refitting commands, because **a precondition
is an answer rather than an exception**.
"""

from __future__ import annotations

__all__ = (
    "register",
)

from mcp.server.fastmcp import FastMCP  # pylint: disable=import-error,no-name-in-module
from mcp.types import ToolAnnotations  # pylint: disable=import-error,no-name-in-module

from mpfbmcp import arguments
from mpfbmcp import backend


def register(mcp: FastMCP) -> None:
    @mcp.tool(
        annotations=ToolAnnotations(
            title="Refit MakeHuman Character",
            readOnlyHint=False,
            destructiveHint=True,
            idempotentHint=True,
            openWorldHint=False,
        )
    )
    def mpfb_refit_human(name: str | None = None) -> dict[str, object]:
        """
        Re-fit everything on a MakeHuman character to the current shape of its
        basemesh: every mesh asset (garments, body parts, the body proxy), the
        rig, and any sub-rigs.

        Call this after changing a character's shape with
        `mpfb_set_macro_details`, `mpfb_set_targets` or
        `mpfb_symmetrize_targets` while leaving their `refit` at its default of
        false - those tools report `assets_possibly_stale` when they leave work
        for this one. A refit re-runs the vertex fit per asset, so make a
        series of modeling changes first and refit once at the end. It is
        idempotent: refitting a character already in fit is safe and costs the
        same.

        `result` carries `refit_performed`, `basemesh_name`, `rig_object_name`,
        `mesh_assets` with `mesh_asset_count`, and `subrigs`.

        **Check `refit_performed` rather than assuming success**; `performed`
        is set from it, so the two cannot disagree. One case refits the mesh
        assets but leaves the rig untouched: a rig generated by Rigify whose
        meta rig is no longer in the scene cannot be refitted at all, and MPFB
        reports this through a channel that does not reach an MCP tool.
        `refit_incomplete_reason` then says so, and the fix - regenerating with
        the meta rig kept - is the user's to make in Blender. A basemesh left
        in edit mode answers with `ready: false`, and an unresolvable subject
        with `found: false`.
        """
        # `result` (built in bridge/mpfb_bridge/commands/refit_human.py) is plain
        # JSON-safe data. The bridge serializes a result before it commits to an
        # answer, so a value that is not JSON-safe would be a failed command
        # rather than a repr() quietly standing in for one.
        return backend.send(
            "refit_human",
            params={"name": arguments.validated_subject(name)},
        )
